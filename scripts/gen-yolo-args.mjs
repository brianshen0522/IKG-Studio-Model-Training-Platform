#!/usr/bin/env node
/**
 * Regenerate packages/shared-types/src/yolo-args.generated.ts from the Ultralytics
 * install inside the training-worker container.
 *
 *   node scripts/gen-yolo-args.mjs
 *
 * The worker validates with the live Ultralytics at run time — that is the authority.
 * This file exists so the browser and the API can reject the same input up front,
 * without shipping Python to either. Re-run it whenever Ultralytics is upgraded; the
 * worker will otherwise reject arguments the UI still believes are valid.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const CONTAINER = process.env.TRAINING_WORKER_CONTAINER || 'deploy-training-worker-1';
const PY = '/app/workers/training-worker/.venv/bin/python';

const script = `
import json
from ultralytics.cfg import (
    DEFAULT_CFG_DICT, CFG_FLOAT_KEYS, CFG_FRACTION_KEYS, CFG_INT_KEYS, CFG_BOOL_KEYS,
)
import ultralytics

args = {}
for key, default in DEFAULT_CFG_DICT.items():
    if key in CFG_BOOL_KEYS:
        kind = 'bool'
    elif key in CFG_INT_KEYS:
        kind = 'int'
    elif key in CFG_FRACTION_KEYS:
        kind = 'fraction'   # numeric, constrained to 0..1
    elif key in CFG_FLOAT_KEYS:
        kind = 'float'
    else:
        kind = 'other'      # strings, paths, None-able knobs: presence-checked only
    args[key] = {'kind': kind, 'default': default if isinstance(default, (int, float, str, bool)) or default is None else str(default)}

print(json.dumps({'ultralyticsVersion': ultralytics.__version__, 'args': args}, sort_keys=True))
`;

const raw = execFileSync('docker', ['exec', CONTAINER, PY, '-c', script], { encoding: 'utf8' });
const spec = JSON.parse(raw.trim().split('\n').pop());

const body = `// GENERATED by scripts/gen-yolo-args.mjs — do not edit by hand.
// Source of truth is the Ultralytics install in the training worker; re-run the script
// after upgrading Ultralytics, or the UI will accept arguments the worker rejects.
//
// kind:
//   bool      CFG_BOOL_KEYS
//   int       CFG_INT_KEYS
//   fraction  CFG_FRACTION_KEYS — numeric, 0..1
//   float     CFG_FLOAT_KEYS
//   other     strings/paths/nullable — only the key name is checked

export interface YoloArgSpec {
  kind: 'bool' | 'int' | 'fraction' | 'float' | 'other';
  default: string | number | boolean | null;
}

export const ULTRALYTICS_VERSION = ${JSON.stringify(spec.ultralyticsVersion)};

export const YOLO_ARGS: Record<string, YoloArgSpec> = ${JSON.stringify(spec.args, null, 2)} as const;
`;

const out = new URL('../packages/shared-types/src/yolo-args.generated.ts', import.meta.url).pathname;
writeFileSync(out, body);
console.log(`wrote ${out}`);
console.log(`ultralytics ${spec.ultralyticsVersion}, ${Object.keys(spec.args).length} arguments`);
